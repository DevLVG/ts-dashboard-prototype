export interface MoaInfo {
  clusterCode: string;
  clusterName: string;
  leafName: string;
}

/** Cluster/leaf names for a MoA code. Falls back to code-derived values for
 * codes missing from the dictionary (e.g. retired codes still in history):
 * cluster = code minus its trailing digits, leaf = the code itself. */
export const moaInfo = (moaCode: string): MoaInfo => {
  const hit = MOA_MASTER[moaCode];
  if (hit) return { clusterCode: hit[0], clusterName: hit[1], leafName: hit[2] };
  const clusterCode = moaCode.replace(/[0-9]+$/, "");
  return { clusterCode, clusterName: clusterCode, leafName: moaCode };
};

/** The Non-Recurring cluster (CFO spec FR-1): GA-NRP = Non-Recurring
 * Professional Fees. Codes in actuals: GA-NRP01; in budget: GA-NRP-HOS,
 * GA-NRP-PD. Prefix match covers both vocabularies. */
export const NON_RECURRING_PREFIX = "GA-NRP";
export const isNonRecurring = (moaCode: string): boolean =>
  moaCode.startsWith(NON_RECURRING_PREFIX);
